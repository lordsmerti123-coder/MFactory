"""
core/hint_engine.py
===================
Модуль: Движок контекстных подсказок.

Отвечает за выдачу подсказок пользователю в зависимости от:
- Конкретного элемента интерфейса (widget_id)
- Текущей панели
- Конфига модели и датасета
- Истории сеансов пользователя
- Текущего значения виджета

Поддерживает 4 режима (переключение в главном окне):
- "static"  — только правило-ориентированные подсказки
- "ai"      — только ИИ-подсказки (через локальную модель, когда будет доступна)
- "hybrid"  — ИИ если доступен, иначе статические (режим по умолчанию)
- "none"    — подсказки отключены

ЗАВИСИМОСТИ (подключаются с защитой):
- core/contracts.py — типы ModelConfig, DatasetMeta, SessionState
- core/session.py   — SessionManager, история сеансов
- core/curator.py   — ИИ-куратор, заглушка под LLM

ПРАВИЛО СБОРКИ:
Модуль обязан работать даже если зависимости ещё не готовы.
Все импорты обёрнуты в try/except. При отсутствии контрактов
используются локальные заглушки типов.
"""

