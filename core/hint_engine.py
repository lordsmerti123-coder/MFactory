    def _get_mode(self, context: HintContext) -> str:
        """Определяет режим подсказок из контекста."""
        # Сначала проверяем сессию
        if context.session is not None and hasattr(context.session, "hint_mode"):
            mode = context.session.hint_mode
            if mode in VALID_MODES:
                return mode

        # Если сессия недоступна — режим по умолчанию
        return DEFAULT_MODE

    def _static_hint(self, context: HintContext) -> str:
        """
        Генерирует правило-ориентированную подсказку.

        Логика:
        1. Берём базовую подсказку из словаря по widget_id
        2. Применяем контекстный модификатор если есть
        3. Адаптируем под уровень пользователя
        """
        widget_id = context.widget_id

        # Ищем базовую подсказку
        hint_data = self._static_hints.get(widget_id)
        if hint_data is None:
            # Пробуем найти по частичному совпадению (для динамических виджетов)
            hint_data = self._find_partial_match(widget_id)

        if hint_data is None:
            logger.debug(f"Подсказка не найдена для элемента: {widget_id}")
            return ""

        base_hint = hint_data.get("default", "")

        # Применяем контекстный модификатор
        modifier = self._modifiers.get(widget_id)
        if modifier is not None:
            try:
                base_hint = modifier(context, base_hint)
            except Exception as e:
                logger.warning(f"Ошибка в модификаторе подсказки для {widget_id}: {e}")

        # Адаптируем под уровень пользователя
        base_hint = self._adapt_for_user_level(context, base_hint)

        return base_hint

    def _ai_hint(self, context: HintContext) -> str:
        """
        Генерирует подсказку через ИИ-бэкенд (куратор или агент Оракула).

        Порядок:
        1. Куратор с llm_backend (если задан);
        2. Агент Оракула (локальная GGUF / внешний API).
        Возвращает пустую строку, если ИИ недоступен.
        """
        prompt = self._build_ai_prompt(context)

        # 1) Куратор
        if self.curator is not None and hasattr(self.curator, "llm_backend") \
                and self.curator.llm_backend is not None:
            try:
                response = self.curator.llm_backend.generate(prompt)
                if response:
                    return f"{response}\n(Автоматическая подсказка от встроенной модели)"
            except Exception as e:
                logger.debug(f"ИИ-подсказка недоступна: {e}")

        # 2) Агент Оракула (локальная GGUF / API)
        agent = self._agent_for_ai()
        if agent is not None:
            try:
                response = agent.generate_free_text(prompt)
                if response:
                    return response.strip()
            except Exception as e:
                logger.debug(f"ИИ-подсказка недоступна (агент): {e}")

        # ИИ недоступен
        return ""

    def _build_ai_prompt(self, context: HintContext) -> str:
        """Формирует промпт для ИИ-модели на основе контекста."""
        parts = [
            f"Пользователь работает с элементом '{context.widget_id}' на панели '{context.panel_name}'.",
        ]

        if context.model_config is not None:
            arch = getattr(context.model_config, "architecture", "неизвестно")
            parts.append(f"Текущая архитектура модели: {arch}.")

        if context.dataset_meta is not None:
            dtype = getattr(context.dataset_meta, "data_type", "неизвестно")
            samples = getattr(context.dataset_meta, "num_samples", 0)
            parts.append(f"Тип данных: {dtype}, количество примеров: {samples}.")

        if context.current_value is not None:
            parts.append(f"Текущее значение: {context.current_value}.")

        parts.append(
            "Дай короткую (1-2 предложения) подсказку для школьника: "
            "что делает этот элемент и какое значение лучше выбрать."
        )

        return " ".join(parts)

    def _find_partial_match(self, widget_id: str) -> Optional[Dict[str, str]]:
        """
        Ищет подсказку по частичному совпадению.
        Полезно для динамически создаваемых виджетов и случаев, когда панель
        передаёт «голое» имя элемента без префикса панели (например, "load_btn"
        вместо "dataset.load_btn").

        Важно: совпадение по суффиксу/хвосту принимается только если оно
        ЕДИНСТВЕННОЕ — иначе «load_btn» мог бы ошибочно вернуть подсказку
        от «project.load_btn» вместо «dataset.load_btn».
        """
        # 1) Префикс: "architecture.tf_heads" -> любой ключ "architecture.*"
        parts = widget_id.rsplit(".", 1)
        if len(parts) == 2:
            prefix = parts[0]
            for key, value in self._static_hints.items():
                if key.startswith(prefix + "."):
                    return value
            return None

        # 2) Суффикс: "load_btn" -> ключ "dataset.load_btn" (только если один)
        suffix = "." + widget_id
        suffix_matches = [v for k, v in self._static_hints.items()
                          if k.endswith(suffix)]
        if len(suffix_matches) == 1:
            return suffix_matches[0]

        # 3) Совпадение по «голове» и «хвосту» имени (независимо от _ / .):
        #    "monitoring_plot_loss" -> "monitoring.loss_plot" (только если один)
        tokens = [t for t in re.split(r"[._]", widget_id) if t]
        if len(tokens) >= 2:
            head, tail = tokens[0], tokens[-1]
            tail_matches = [
                v for k, v in self._static_hints.items()
                if (lambda kt: len(kt) >= 2 and kt[0] == head and kt[-1] == tail)(
                    [t for t in re.split(r"[._]", k) if t]
                )
            ]
            if len(tail_matches) == 1:
                return tail_matches[0]
        return None

    def _adapt_for_user_level(self, context: HintContext, hint: str) -> str:
        """
        Адаптирует подсказку под уровень пользователя.

        - Новичок (1-2 сеанса): подробные подсказки с аналогиями
        - Средний (3-10 сеансов): стандартные подсказки
        - Продвинутый (>10 сеансов): краткие подсказки
        - Если были ошибки с этим элементом: дополнительные советы
        """
        session = context.session
        if session is None:
            return hint

        total_sessions = getattr(session, "total_sessions", 0)
        mistakes = getattr(session, "mistakes_count", 0)

        # Новичок — добавляем ободряющий суффикс
        if total_sessions <= 2:
            hint += _BEGINNER_SUFFIX

        # Продвинутый — убираем лишние пояснения (подсказка уже краткая)
        # Ничего не добавляем

        # Если были ошибки — добавляем предупреждение
        if mistakes > 3:
            hint += _ERROR_PRONE_SUFFIX

        return hint

