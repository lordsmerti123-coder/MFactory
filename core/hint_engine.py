    def validate_coverage(self, required_widgets: List[str]) -> Dict[str, bool]:
        """
        Проверяет, что для всех переданных виджетов есть подсказки.
        Используется при тестировании интеграции.

        Args:
            required_widgets: список обязательных виджетов

        Returns:
            словарь {widget_id: есть_подсказка}
        """
        result = {}
        for widget_id in required_widgets:
            hint_data = self._static_hints.get(widget_id)
            result[widget_id] = hint_data is not None
        return result

    def get_all_widget_ids(self) -> List[str]:
        """Возвращает список всех виджетов, для которых есть подсказки."""
        return list(self._static_hints.keys())

    def get_hint_count(self) -> int:
        """Возвращает количество подсказок в базе."""
        return len(self._static_hints)