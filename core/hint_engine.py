class HintEngine:
    """
    Движок контекстных подсказок.

    Режимы работы:
    - "static": только правило-ориентированные подсказки (без ИИ)
    - "ai": только ИИ-подсказки (когда бэкенд доступен)
    - "hybrid": ИИ если доступен, иначе статические (по умолчанию)
    - "none": подсказки отключены

    Использование из GUI (gui/hint_widget.py):
        context = HintContext(
            widget_id="hyperparams.lr",
            panel_name="hyperparams_panel",
            model_config=shared_state.get("config"),
            dataset_meta=shared_state.get("dataset", {}).get("meta"),
            session=shared_state.get("session"),
            current_value=self.lr_spin.value(),
        )
        hint = hint_engine.get_hint(context)
        tooltip = hint  # показать как tooltip
    """

    def __init__(self, session_manager=None, curator=None):
        """
        Args:
            session_manager: SessionManager из core/session.py (может быть None)
            curator: Curator из core/curator.py (может быть None)
        """
        self.session_manager = session_manager
        self.curator = curator
        self._static_hints = STATIC_HINTS
        self._modifiers = _MODIFIERS
        self._hint_cache: Dict[str, str] = {}

        logger.info(
            f"HintEngine инициализирован. "
            f"Подсказок в базе: {len(self._static_hints)}. "
            f"Контракты доступны: {CONTRACTS_AVAILABLE}. "
            f"Куратор доступен: {CURATOR_AVAILABLE}."
        )

    # ============================================================
    #  ИИ-АГЕНТ (для ИИ-подсказок)
    # ============================================================
    # Панели могут создавать собственные HintEngine, поэтому агент хранится
    # на уровне класса: один экземпляр OraculumAgent на всё приложение.
    _default_agent = None  # type: ignore

    @classmethod
    def set_default_agent(cls, agent) -> None:
        """Подключает агента Оракула для генерации ИИ-подсказок."""
        cls._default_agent = agent

    def _agent_for_ai(self):
        """Возвращает агента для ИИ-подсказок (если задан)."""
        return HintEngine._default_agent

    # ============================================================
    #  ПУБЛИЧНЫЙ ИНТЕРФЕЙС
    # ============================================================

    def get_hint(self, context: HintContext) -> str:
        """
        Возвращает подсказку для заданного контекста.

        Args:
            context: HintContext с информацией о виджете и состоянии.

        Returns:
            Текст подсказки. Пустая строка если режим "none" или подсказка не найдена.
        """
        # Определяем режим
        mode = self._get_mode(context)

        if mode == HINT_MODE_NONE:
            return ""

        if mode == HINT_MODE_STATIC:
            return self._static_hint(context)

        if mode == HINT_MODE_AI:
            ai_hint = self._ai_hint(context)
            if ai_hint:
                return ai_hint
            # В режиме "только ИИ" если ИИ недоступен — показываем сообщение
            return "🤖 ИИ-подсказки недоступны (модель не подключена)."

        # Режим "hybrid" (по умолчанию)
        ai_hint = self._ai_hint(context)
        if ai_hint:
            return f"🤖 {ai_hint}"
        return self._static_hint(context)

    def get_mode(self, context: HintContext) -> str:
        """Возвращает текущий режим подсказок."""
        return self._get_mode(context)

    def set_mode_in_session(self, session, mode: str) -> bool:
        """
        Устанавливает режим подсказок в сессии.

        Args:
            session: SessionState
            mode: один из "static", "ai", "hybrid", "none"

        Returns:
            True если режим установлен, False если некорректный.
        """
        if mode not in VALID_MODES:
            logger.warning(f"Некорректный режим подсказок: {mode}. Ожидается один из {VALID_MODES}.")
            return False

        if session is not None and hasattr(session, "hint_mode"):
            session.hint_mode = mode
            logger.info(f"Режим подсказок изменён на '{mode}'.")
            self._hint_cache.clear()  # сбрасываем кэш при смене режима
            return True
        return False

    def get_available_modes(self) -> List[str]:
        """Возвращает список доступных режимов для GUI."""
        return VALID_MODES.copy()

