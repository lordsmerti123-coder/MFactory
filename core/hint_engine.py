# Функции, которые изменяют подсказку в зависимости от контекста.
# Каждая принимает HintContext и базовую подсказку, возвращает изменённую.

def _mod_lr(context: HintContext, base_hint: str) -> str:
    """Модификатор для скорости обучения в зависимости от контекста."""
    lr = context.current_value
    if lr is None:
        return base_hint

    # Определяем архитектуру
    arch = ""
    if context.model_config is not None:
        arch = getattr(context.model_config, "architecture", "")
        if isinstance(arch, str):
            arch = arch.lower()
        else:
            arch = str(arch).lower()

    # Слишком высокий LR для Трансформера
    if lr > 0.01 and "transformer" in arch:
        return (
            "⚠️ Слишком высоко для Трансформера! При такой скорости сеть, скорее всего, "
            "разойдётся — графики улетят в бесконечность. Попробуйте 0.0001–0.001."
        )

    # Слишком низкий LR
    if lr < 0.00001:
        return (
            "🐢 Очень маленькая скорость. Обучение может занять вечность. "
            "Для стандартных задач попробуйте 0.001–0.01."
        )

    # Слишком высокий для любой модели
    if lr > 0.1:
        return (
            "⚠️ Очень высокая скорость обучения. Сеть может «перепрыгивать» правильные ответы "
            "и не научиться. Рекомендуется 0.001–0.01."
        )

    # Нормальные значения
    if 0.0001 <= lr <= 0.01:
        return base_hint + " ✅ Текущее значение выглядит разумным."

    return base_hint


def _mod_epochs(context: HintContext, base_hint: str) -> str:
    """Модификатор для количества эпох."""
    epochs = context.current_value
    if epochs is None:
        return base_hint

    if epochs > 500:
        return (
            "⚠️ Очень много эпох. Скорее всего, сеть переобучится (вызубрит ответы). "
            "Если это не специальный эксперимент, лучше 50–200."
        )

    if epochs < 5:
        return (
            "🤔 Очень мало эпох. Сеть может не успеть выучить даже основы. "
            "Минимум 10–20 для простых задач."
        )

    return base_hint


def _mod_batch_size(context: HintContext, base_hint: str) -> str:
    """Модификатор для размера батча."""
    batch = context.current_value
    if batch is None:
        return base_hint

    if batch > 256:
        return (
            "⚠️ Большой батч. Нужно много видеопамяти. "
            "Если не хватает памяти — уменьшите до 64 или 32."
        )

    if batch < 8:
        return (
            "🐢 Очень маленький батч. Обучение будет медленным и шумным. "
            "Рекомендуется 32–128."
        )

    return base_hint


def _mod_dropout(context: HintContext, base_hint: str) -> str:
    """Модификатор для дропаута."""
    dropout = context.current_value
    if dropout is None:
        return base_hint

    if dropout > 0.5:
        return (
            "⚠️ Очень сильный dropout. Сеть может не научиться вообще — "
            "слишком много нейронов отключается. Рекомендуется 0.1–0.3."
        )

    if dropout == 0.0:
        return (
            "Dropout выключен. Для маленьких датасетов сеть может зубрить. "
            "Если увидите переобучение — поставьте 0.1–0.3."
        )

    return base_hint


def _mod_train_split(context: HintContext, base_hint: str) -> str:
    """Модификатор для процента обучения при маленьком датасете."""
    meta = context.dataset_meta
    if meta is None:
        return base_hint

    num_samples = getattr(meta, "num_samples", 0)
    if num_samples > 0 and num_samples < 100:
        return (
            "⚠️ У вас очень мало данных (< 100 примеров). "
            "Рекомендуется использовать 90% для обучения и 5/5 для проверки/теста, "
            "чтобы не потерять примеры."
        )

    return base_hint


def _mod_vocab_limit(context: HintContext, base_hint: str) -> str:
    """Модификатор для ограничения словаря."""
    value = context.current_value
    if value is None:
        return base_hint

    if value < 20:
        return (
            "⚠️ Очень маленький словарь. Почти все символы станут <UNK>. "
            "Сеть не сможет читать текст. Минимум 20–30."
        )

    return base_hint


def _mod_teacher_forcing(context: HintContext, base_hint: str) -> str:
    """Модификатор для Teacher Forcing."""
    value = context.current_value
    if value is None:
        return base_hint

    if value >= 1.0:
        return (
            "Учитель всегда подсказывает правильный ответ. Сеть учится быстро, "
            "но может «растеряться», когда придётся писать самой. "
            "Для надёжности снижайте до 0.5–0.7 к концу обучения."
        )

    if value <= 0.0:
        return (
            "Учитель не подсказывает вообще. Сеть пишет сама с нуля. "
            "Сложнее учиться, но результат надёжнее. "
            "Для начала поставьте 0.5–0.7."
        )

    return base_hint


