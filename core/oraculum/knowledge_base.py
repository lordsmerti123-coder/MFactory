class KnowledgeBase:
    """Локальная база знаний Оракула. Поиск по ключевым словам."""

    def __init__(self, entries: Optional[List[Dict[str, Any]]] = None):
        self.entries = list(entries if entries is not None else KNOWLEDGE_ENTRIES)

    # ============================================================
    # ПОИСК
    # ============================================================
    def search(self, query: str, min_score: float = 1.0) -> Optional[str]:
        """
        Ищет лучшую запись по совпадению ключевых слов с запросом.

        Возвращает answer лучшей записи, если совпадение достаточно сильное,
        иначе None. min_score — порог уверенности: 1.0 = хотя бы одно
        ключевое слово/фраза совпало.
        """
        q = (query or "").lower().strip()
        if not q:
            return None

        query_stems = _stems(q)
        best_answer: Optional[str] = None
        best_score = 0.0

        for entry in self.entries:
            score = self._score_entry(entry, q, query_stems)
            if score > best_score:
                best_score = score
                best_answer = entry.get("answer")

        if best_answer is not None and best_score >= min_score:
            return best_answer
        return None

    def _score_entry(self, entry: Dict[str, Any], query_lower: str,
                     query_stems: set) -> float:
        """Оценка записи: сумма весов совпавших ключевых слов/фраз.

        Фраза (несколько слов) считается совпавшей, если все её слова
        встречаются в запросе (с учётом стемминга) — сильное совпадение (2.0).
        Одиночное слово: точная подстрока (1.5) либо совпадение основ (1.0).
        """
        hits = 0.0
        for kw in entry.get("keywords", []):
            kw_l = (kw or "").lower().strip()
            if not kw_l:
                continue
            words = [w for w in re.findall(r"[а-яёa-z0-9]+", kw_l)
                     if len(w) >= 3]
            if not words:
                continue

            if len(words) > 1:
                # Фраза: все слова должны встретиться в запросе
                if all(any(_stem_match(_stem(w), q) for q in query_stems)
                       for w in words):
                    hits += 2.0
            else:
                s = _stem(words[0])
                if len(s) >= 4 and s in query_lower:
                    hits += 1.5
                elif any(_stem_match(s, q) for q in query_stems):
                    hits += 1.0
        return hits

    def all_answers(self) -> List[str]:
        """Все ответы (для отладки/экспорта)."""
        return [e["answer"] for e in self.entries if e.get("answer")]

    def count(self) -> int:
        return len(self.entries)


