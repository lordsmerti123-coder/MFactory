# ============================================================
# Нужен, чтобы «нейросети/нейросеть/нейросетей», «выбрать/выбирать»,
# «модель/модели» находились по одному и тому же ключу.

_RU_SUFFIXES = (
    "иями", "ями", "ами", "иях", "ях", "ах", "ией", "ей", "её", "ий", "ый",
    "ой", "ая", "яя", "ое", "ее", "ие", "ые", "ье", "ья", "ью", "ию", "ую",
    "юю", "ого", "его", "ому", "ему", "ыми", "ими", "ым", "им", "ов", "ев",
    "ам", "ям", "ом", "ем", "ть", "ти", "чь",
    "а", "я", "ы", "и", "у", "ю", "о", "е", "ь", "й", "ъ",
)


def _stem(word: str) -> str:
    """Отбрасывает типичные русские окончания, оставляя основу слова."""
    w = word.lower()
    for suf in _RU_SUFFIXES:
        if w.endswith(suf) and len(w) - len(suf) >= 3:
            return w[: len(w) - len(suf)]
    return w


def _stems(text: str) -> set:
    """Множество основ всех слов текста (длина >= 3)."""
    return {_stem(w) for w in re.findall(r"[а-яёa-z0-9]+", text.lower())
            if len(w) >= 3}


def _stem_match(a: str, b: str) -> bool:
    """Совпадение основ: равенство или общий префикс (мин. 4 символа)."""
    if a == b:
        return True
    if len(a) >= 4 and len(b) >= 4:
        return a.startswith(b) or b.startswith(a)
    return False


